    public static final int SIZE = 9;

    private final boolean[][] pixels = new boolean[SIZE][SIZE];

    Icon(String... rows) {
        for (int y = 0; y < SIZE; y++) {
            for (int x = 0; x < SIZE; x++) {
                pixels[y][x] = rows[y].charAt(x) == '#';
            }
        }
    }

    boolean at(int x, int y) {
        return pixels[y][x];
    }
